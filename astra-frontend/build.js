#!/usr/bin/env node
/* Build the ASTRA static frontend for Cloudflare Pages.

Reads BACKEND_BASE from the environment (Cloudflare Pages env var) and emits
`dist/config.js`, then copies the static assets into `dist/`. The production
value points at the Railway HTTPS endpoint. Local preview:

    BACKEND_BASE=https://... node build.js   # writes dist/
    BACKEND_BASE=https://... npx wrangler pages dev dist
*/

const fs = require("fs");
const path = require("path");

const root = __dirname;
const dist = path.join(root, "dist");
const backend = process.env.BACKEND_BASE || "";
const refreshMs = process.env.ASTRA_REFRESH_MS || "30000";

fs.rmSync(dist, { recursive: true, force: true });
fs.mkdirSync(dist, { recursive: true });
fs.mkdirSync(path.join(dist, "assets"), { recursive: true });

const configJs = `// Generated by build.js from the BACKEND_BASE environment variable.
window.ASTRA_BACKEND_BASE = ${JSON.stringify(backend)};
window.ASTRA_REFRESH_MS = ${Number(refreshMs) || 30000};
`;
fs.writeFileSync(path.join(dist, "config.js"), configJs);

fs.copyFileSync(path.join(root, "index.html"), path.join(dist, "index.html"));
fs.copyFileSync(path.join(root, "assets", "app.css"), path.join(dist, "assets", "app.css"));
fs.copyFileSync(path.join(root, "assets", "app.js"), path.join(dist, "assets", "app.js"));

console.log(`Built dist/ with BACKEND_BASE=${backend ? "configured" : "NOT CONFIGURED"}`);
console.log("Files:", fs.readdirSync(dist).join(", "), "/ assets:",
            fs.readdirSync(path.join(dist, "assets")).join(", "));