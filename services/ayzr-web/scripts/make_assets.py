"""Generate AYZR visual assets with Pillow.

These are drawn programmatically, not generated by an AI image model. That is a
deliberate choice: the shapes here are logos, icons and a chart backdrop, where
exact geometry and crisp edges matter more than photographic detail, and where a
diffusion model would only introduce blur and licence ambiguity.
"""
from __future__ import annotations
import math
from pathlib import Path
from PIL import Image, ImageDraw, ImageFilter, ImageFont

OUT = Path(__file__).resolve().parent.parent / "static" / "assets"
OUT.mkdir(parents=True, exist_ok=True)

GOLD = (212, 175, 55)
GOLD_LIGHT = (240, 210, 120)
NAVY = (10, 16, 30)
NAVY_MID = (18, 28, 48)
GREEN = (34, 197, 94)
RED = (239, 68, 68)


def font(size: int):
    for p in (
        "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
        "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
    ):
        if Path(p).exists():
            return ImageFont.truetype(p, size)
    return ImageFont.load_default()


def radial(size, inner, outer):
    """Soft radial glow, built by per-pixel distance so it stays smooth."""
    img = Image.new("RGB", (size, size), outer)
    px = img.load()
    c = size / 2
    for y in range(size):
        for x in range(size):
            d = math.hypot(x - c, y - c) / c
            t = max(0.0, 1.0 - d)
            t = t * t
            px[x, y] = tuple(int(outer[i] + (inner[i] - outer[i]) * t) for i in range(3))
    return img


def logo(size=512):
    """A stylised gold ingot over a glow: readable down to 48px."""
    img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    glow = radial(size, NAVY_MID, (0, 0, 0)).convert("RGBA")
    mask = Image.new("L", (size, size), 0)
    ImageDraw.Draw(mask).ellipse([size*0.06]*2 + [size*0.94]*2, fill=255)
    mask = mask.filter(ImageFilter.GaussianBlur(size // 14))
    img.paste(glow, (0, 0), mask)

    d = ImageDraw.Draw(img)
    m = size * 0.22
    # Trapezoid ingot.
    top_y, bot_y = m * 1.25, size - m
    top_inset, bot_inset = m * 0.55, 0
    pts = [
        (m + top_inset, top_y), (size - m - top_inset, top_y),
        (size - m - bot_inset, bot_y), (m + bot_inset, bot_y),
    ]
    d.polygon(pts, fill=GOLD)
    d.line(pts + [pts[0]], fill=GOLD_LIGHT, width=max(2, size // 110), joint="curve")
    # Facet highlight.
    d.line([pts[0], pts[3]], fill=GOLD_LIGHT, width=max(1, size // 200))
    for i in range(1, 4):
        y = top_y + (bot_y - top_y) * i / 4
        d.line([(m + top_inset * (1 - i/4), y), (size - m - top_inset * (1 - i/4), y)],
               fill=(180, 145, 40), width=max(1, size // 220))
    img.save(OUT / "logo.png")

    for s in (192, 96, 48):
        img.resize((s, s), Image.LANCZOS).save(OUT / f"logo-{s}.png")
    return img


def icon(name, draw_fn, size=128):
    img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    draw_fn(d, size)
    img.save(OUT / f"icon-{name}.png")


def home(d, s):
    d.polygon([(s*.5, s*.2), (s*.85, s*.48), (s*.72, s*.48), (s*.72, s*.8), (s*.28, s*.8), (s*.28, s*.48), (s*.15, s*.48)], fill=GOLD)

def chart(d, s):
    d.line([(s*.15, s*.8), (s*.85, s*.8)], fill=GOLD, width=int(s*.05))
    d.line([(s*.15, s*.8), (s*.15, s*.2)], fill=GOLD, width=int(s*.05))
    for x, h in ((.3,.35),(.45,.55),(.6,.42),(.75,.68)):
        d.rectangle([s*x-int(s*.045), s*(.8-h), s*x+int(s*.045), s*.78], fill=GOLD_LIGHT)

def news(d, s):
    d.rounded_rectangle([s*.16, s*.2, s*.84, s*.8], radius=int(s*.06), fill=GOLD)
    for y in (.34, .46, .58, .7):
        d.line([(s*.28, s*y), (s*.72, s*y)], fill=NAVY, width=int(s*.04))

def history(d, s):
    d.ellipse([s*.18, s*.18, s*.82, s*.82], outline=GOLD, width=int(s*.06))
    d.line([(s*.5, s*.32), (s*.5, s*.52), (s*.66, s*.62)], fill=GOLD_LIGHT, width=int(s*.055), joint="curve")

def shield(d, s):
    d.polygon([(s*.5, s*.15), (s*.82, s*.3), (s*.78, s*.62), (s*.5, s*.86), (s*.22, s*.62), (s*.18, s*.3)], fill=GOLD)
    d.line([(s*.34, s*.5), (s*.46, s*.62), (s*.68, s*.36)], fill=NAVY, width=int(s*.07), joint="curve")


def hero(size=(1200, 420)):
    """Backdrop for the site header: grid + gold glow, no text baked in."""
    img = Image.new("RGB", size, NAVY)
    d = ImageDraw.Draw(img)
    for x in range(0, size[0], 40):
        d.line([(x, 0), (x, size[1])], fill=(20, 30, 52), width=1)
    for y in range(0, size[1], 40):
        d.line([(0, y), (size[0], y)], fill=(20, 30, 52), width=1)
    glow = radial(size[1], NAVY_MID, (0, 0, 0)).convert("RGB")
    img.paste(Image.blend(img.crop((size[0]//2 - size[1]//2, 0, size[0]//2 + size[1]//2, size[1])), glow, 0.45),
              (size[0]//2 - size[1]//2, 0))
    d = ImageDraw.Draw(img)
    # Synthetic-looking but clearly decorative trend line, not a data claim.
    pts, base = [], size[1] * 0.7
    for i in range(0, size[0], 12):
        t = i / size[0]
        pts.append((i, base - math.sin(t * 6) * 40 - t * 90 + math.sin(t * 23) * 8))
    d.line(pts, fill=GOLD, width=3, joint="curve")
    img.save(OUT / "hero.jpg", quality=88)
    return img


if __name__ == "__main__":
    logo()
    icon("home", home); icon("chart", chart); icon("news", news)
    icon("history", history); icon("shield", shield)
    hero()
    print("assets:", sorted(p.name for p in OUT.iterdir()))
